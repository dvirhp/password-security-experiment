"""
ProtectionHandler Module

Handles various security protections for authentication systems, including:
- Rate limiting
- User lockouts
- CAPTCHA challenges
- TOTP (Time-based One-Time Password)
"""

from .rate_limit import RateLimiter
from .lockout import Lockout
from .captcha import Captcha
from .totp import Totp

# Mapping of protection names to their classes
PROTECTIONS_CLASSES = {
    "rate_limit": RateLimiter,
    "lockout": Lockout,
    "captcha": Captcha,
    "totp": Totp
}


class ProtectionHandler:
    """
    Manages all security protections for a given authentication system.

    Initialize instances for each protection based on configuration and
    provides helper methods for interaction during login attempts.
    """

    def __init__(self, protections):
        """
        Initialize ProtectionHandler with protection configurations.

        Args:
            protections (dict): Dictionary mapping protection names to parameters.
        """
        self._protections = protections
        self._instances = {}

        self._initialize_instances()

    def _initialize_protection(self, protection):
        """
        Initialize a single protection instance.

        Args:
            protection (str): Name of the protection to initialize.

        Returns:
            An instance of the protection class, or None if no parameters are provided.

        Raises:
            ValueError: If protection name is invalid.
        """
        protection_class = PROTECTIONS_CLASSES.get(protection)

        if protection_class is None:
            raise ValueError(f"Invalid protection class in protection.py: {protection}")

        params = self._protections.get(protection, [])
        return protection_class(params) if params else None

    def _initialize_instances(self):
        """Initialize instances for all known protections."""
        for name in PROTECTIONS_CLASSES:
            self._instances[name] = self._initialize_protection(name)

    @property
    def rate_limiter(self):
        return self._instances["rate_limit"]

    @property
    def lockout(self):
        return self._instances["lockout"]

    @property
    def captcha(self):
        return self._instances["captcha"]

    @property
    def totp(self):
        return self._instances["totp"]

    @property
    def totp_enabled(self):
        """
        Check if TOTP protection is enabled.

        Returns:
            bool: True if TOTP is active, False otherwise.
        """
        return self.totp is not None

    def rate_limiter_allow_request(self, ip_address):
        """
        Check if a request is allowed by rate limiter.

        Args:
            ip_address (str): Client IP address.

        Returns:
            bool: True if request should be blocked, False otherwise.
        """
        return self.rate_limiter and not self.rate_limiter.allow_request(ip_address)

    def handle_lockout(self, response_handler, verify_callable, ip_address, username, start_time):
        """
        Handle lockout logic during a login attempt.

        Args:
            response_handler: Object responsible for sending responses (login success, fail, etc.).
            verify_callable: Callable to verify user credentials (e.g., password check).
            ip_address (str): Client IP address.
            username (str): Username attempting login.
            start_time (float): Timestamp of login attempt start.

        Returns:
            Response generated by the response_handler.
        """
        allowed, message = self.lockout.allow_attempt(username)
        if not allowed:
            return response_handler.login_lockout(ip_address, username, message, start_time)
        elif verify_callable():
            if self.totp_required(username):
                return response_handler.login_totp_required(ip_address, username, start_time)

            self.lockout.reset_after_successful_login(username)
            return response_handler.login_success(ip_address, username, start_time)

        self.lockout.lock_user(username)
        return response_handler.login_fail(ip_address, username, start_time)

    def captcha_required(self, ip_address):
        """
        Check if CAPTCHA is required for the given IP.

        Args:
            ip_address (str): Client IP.

        Returns:
            bool: True if CAPTCHA is required.
        """
        return self.captcha and self.captcha.captcha_required(ip_address)

    def captcha_register_failure(self, ip_address):
        """
        Register a failed CAPTCHA attempt for the IP.

        Args:
            ip_address (str): Client IP.
        """
        if self.captcha:
            self.captcha.register_failure(ip_address)

    def captcha_blocked(self, ip_address):
        """
        Check if CAPTCHA access is blocked for an IP.

        Args:
            ip_address (str): Client IP.

        Returns:
            bool: True if blocked.
        """
        if self.captcha:
            return self.captcha.captcha_blocked(ip_address)

    def register_totp_if_needed(self, member):
        """
        Register TOTP for a member if TOTP is enabled and the member has a secret.

        Args:
            member (dict): Member info with 'username' and 'totp_secret'.
        """
        if self.totp is None:
            return

        totp_secret = member["totp_secret"]

        if totp_secret is not None:
            self.totp.register_user(member["username"], totp_secret)

    def totp_required(self, username):
        """
        Check if TOTP verification is required for a given user.

        Args:
            username (str): Username.

        Returns:
            bool: True if TOTP is enabled and required.
        """
        return self.totp and self.totp.totp_enabled(username)
